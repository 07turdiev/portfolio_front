// One-time data-prep: turns d:/Sites/Portfolio/data/* into app-ready assets.
//  - splits the 13MB districts.js into per-region JSON files (lazy-loaded)
//  - copies region SVG paths into a small bundled module
//  - generates mock per-direction / per-region / per-district counts
import { writeFileSync, mkdirSync } from 'fs'
import { fileURLToPath, pathToFileURL } from 'url'
import { dirname, join } from 'path'

const here = dirname(fileURLToPath(import.meta.url))
const DATA_DIR = join(here, '../../data')
const PUBLIC_API = join(here, '../public/api')
const SRC_DATA = join(here, '../src/data')

const { DISTRICTS } = await import(pathToFileURL(join(DATA_DIR, 'districts.js')).href)
const { REGIONS } = await import(pathToFileURL(join(DATA_DIR, 'regions.js')).href)

mkdirSync(join(PUBLIC_API, 'districts'), { recursive: true })
mkdirSync(SRC_DATA, { recursive: true })

// 1. Per-region district SVG maps -> public/api/districts/<region>.json
for (const [regionKey, data] of Object.entries(DISTRICTS)) {
  writeFileSync(
    join(PUBLIC_API, 'districts', `${regionKey}.json`),
    JSON.stringify({ viewBox: data.viewBox, districts: data.districts })
  )
}

// 2. Country-level region SVG paths -> bundled module (small)
const regionsOut = Object.entries(REGIONS).map(([key, r]) => ({
  key,
  name: r.name,
  svgId: r.svgId,
  labelX: r.labelX,
  labelY: r.labelY,
  path: r.path
}))
writeFileSync(
  join(SRC_DATA, 'uzbekistanRegions.js'),
  `// Auto-generated by scripts/prepare-map-data.mjs — do not edit by hand.\n` +
    `export const REGION_VIEWBOX = '0 0 892.49 580.88'\n` +
    `export const REGIONS = ${JSON.stringify(regionsOut)}\n`
)

// 3. Mock counts: directions -> regions -> districts
const DIRECTIONS = [
  { key: 'theater_circus', icon: 'theater', perDistrict: 15 },
  { key: 'education', icon: 'education', perDistrict: 61 },
  { key: 'heritage', icon: 'heritage', perDistrict: 12 },
  { key: 'cinema', icon: 'cinema', perDistrict: 9 },
  { key: 'concert', icon: 'concert', perDistrict: 26 }
]

function makeRng(seed) {
  let h = 2166136261 >>> 0
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return () => {
    h += 0x6d2b79f5
    let t = h
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const directions = DIRECTIONS.map((dir) => {
  const regions = Object.entries(DISTRICTS).map(([regionKey, regionData]) => {
    const districts = regionData.districts.map((d) => {
      const rng = makeRng(`${dir.key}:${d.id}`)
      const total = Math.max(3, Math.round(dir.perDistrict * (0.45 + rng() * 1.4)))
      const men = Math.round(total * (0.42 + rng() * 0.16))
      const women = total - men
      return { id: d.id, name: d.name, men, women }
    })
    const men = districts.reduce((s, x) => s + x.men, 0)
    const women = districts.reduce((s, x) => s + x.women, 0)
    return { key: regionKey, men, women, districts }
  })
  return { key: dir.key, icon: dir.icon, regions }
})

writeFileSync(
  join(PUBLIC_API, 'portfolio-data.json'),
  JSON.stringify({ directions })
)

const totalDistricts = Object.values(DISTRICTS).reduce(
  (s, r) => s + r.districts.length,
  0
)
console.log(
  `Done. regions=${regionsOut.length}, districtMaps=${
    Object.keys(DISTRICTS).length
  }, districts=${totalDistricts}`
)
